var DICTS = { de: DE, en: EN };
var LANGUAGES = [{ code: 'de', name: 'Deutsch' }, { code: 'en', name: 'English' }];

function normLang(lang) {
  return DICTS[lang] ? lang : 'en';
}

// Language from the host UI locale, e.g. "de_DE" -> "de".
function langFromLocale(locale) {
  return /^de/i.test(String(locale || '')) ? 'de' : 'en';
}

function t(lang, key, params, host) {
  var dict = DICTS[normLang(lang)];
  params = params || {};
  var k = key;
  if (params.n !== undefined && (dict[key + '_one'] || dict[key + '_other'])) {
    k = key + (params.n === 1 ? '_one' : '_other');
  }
  var text = (host === 'AEFT' && dict[k + '_ae'] !== undefined) ? dict[k + '_ae'] : dict[k];
  if (text === undefined) text = EN[k] !== undefined ? EN[k] : key;
  return String(text).replace(/\{(\w+)\}/g, function (m, name) {
    return params[name] !== undefined ? String(params[name]) : m;
  });
}

module.exports = { t: t, LANGUAGES: LANGUAGES, langFromLocale: langFromLocale, normLang: normLang, DICTS: DICTS };
